
from pathlib import Path
import json
import hashlib

import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parents[2]
RAW_DIR = PROJECT_ROOT / "data" / "raw"
PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
REPORTS_DIR = PROJECT_ROOT / "reports"

RANDOM_SEED = 20261022


def calculate_checksum(file_path):
    sha256 = hashlib.sha256()

    with open(file_path, "rb") as file:
        for chunk in iter(lambda: file.read(4096), b""):
            sha256.update(chunk)

    return sha256.hexdigest()


def main():
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)

    manifest = {
        "project": "Logistics ETA Prediction and Delay Detection",
        "random_seed": RANDOM_SEED,
        "generation_method": "Synthetic data generated using Python and Pandas",
        "datasets": [],
    }

    folders = [
        ("raw", RAW_DIR),
        ("processed", PROCESSED_DIR),
    ]

    for dataset_type, folder in folders:

        if not folder.exists():
            continue

        for file_path in sorted(folder.glob("*.csv")):

            dataframe = pd.read_csv(file_path)

            manifest["datasets"].append({
                "dataset_name": file_path.stem,
                "dataset_type": dataset_type,
                "file_name": file_path.name,
                "record_count": len(dataframe),
                "column_count": len(dataframe.columns),
                "columns": dataframe.columns.tolist(),
                "sha256": calculate_checksum(file_path),
                "generation_method": (
                    "Synthetic dataset generated by project pipeline"
                    if dataset_type == "raw"
                    else "Derived from raw source datasets"
                ),
            })

    output_path = REPORTS_DIR / "source_manifest.json"

    with open(output_path, "w", encoding="utf-8") as file:
        json.dump(manifest, file, indent=4, default=str)

    print("\nSOURCE MANIFEST GENERATED")
    print("-------------------------")
    print("Total datasets:", len(manifest["datasets"]))
    print("Output:", output_path)

    for dataset in manifest["datasets"]:
        print(
            dataset["dataset_name"],
            "->",
            dataset["record_count"],
            "records"
        )


if __name__ == "__main__":
    main()
