
import pandas as pd


def filter_known_events(events, prediction_at):
    """
    Return only non-duplicate tracking events that were both:
    1. Generated by prediction time.
    2. Ingested by prediction time.
    """
    prediction_at = pd.to_datetime(prediction_at, utc=True)

    known = events.copy()

    known["event_at"] = pd.to_datetime(
        known["event_at"], utc=True
    )
    known["ingested_at"] = pd.to_datetime(
        known["ingested_at"], utc=True
    )

    if "is_duplicate" in known.columns:
        duplicate_flags = (
            known["is_duplicate"].astype(str).str.lower()
            == "true"
        )
        known = known[~duplicate_flags]

    return known[
        (known["event_at"] <= prediction_at)
        & (known["ingested_at"] <= prediction_at)
    ].copy()


def validate_route_sequence(shipment_legs, routes):
    """
    Verify that each shipment's legs form a connected route
    and use consecutive leg sequence numbers.
    """
    route_lookup = routes.set_index("route_id").to_dict("index")

    for shipment_id, legs in shipment_legs.groupby("shipment_id"):

        legs = legs.sort_values("leg_sequence")

        sequences = legs["leg_sequence"].tolist()

        expected = list(range(1, len(sequences) + 1))

        if sequences != expected:
            raise ValueError(
                f"{shipment_id}: invalid leg sequence"
            )

        previous_destination = None

        for _, leg in legs.iterrows():

            route_id = leg["route_id"]

            if route_id not in route_lookup:
                raise ValueError(
                    f"{shipment_id}: unknown route {route_id}"
                )

            route = route_lookup[route_id]

            if previous_destination is not None:
                if route["origin_facility_id"] != previous_destination:
                    raise ValueError(
                        f"{shipment_id}: disconnected route "
                        f"at leg {leg['leg_id']}"
                    )

            previous_destination = route[
                "destination_facility_id"
            ]


def validate_shipment_lifecycle(shipments, events):
    """
    Verify that shipment status agrees with delivery events.
    """
    delivered_event_ids = set(
        events.loc[
            events["event_type"] == "DELIVERED",
            "shipment_id"
        ]
    )

    for _, shipment in shipments.iterrows():

        shipment_id = shipment["shipment_id"]
        status = shipment["current_status"]
        actual_delivery = shipment["actual_delivery_at"]

        has_delivery_event = (
            shipment_id in delivered_event_ids
        )

        if status == "DELIVERED":

            if pd.isna(actual_delivery):
                raise ValueError(
                    f"{shipment_id}: delivered shipment "
                    "has no actual delivery time"
                )

            if not has_delivery_event:
                raise ValueError(
                    f"{shipment_id}: delivered shipment "
                    "has no DELIVERED event"
                )

        elif status == "IN_TRANSIT":

            if pd.notna(actual_delivery):
                raise ValueError(
                    f"{shipment_id}: in-transit shipment "
                    "has an actual delivery time"
                )

            if has_delivery_event:
                raise ValueError(
                    f"{shipment_id}: in-transit shipment "
                    "has a DELIVERED event"
                )

        else:
            raise ValueError(
                f"{shipment_id}: unsupported shipment status {status}"
            )
